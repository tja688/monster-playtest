  function glyph(ch) {
    return GLYPHS[ch] || null;
  }

  function advance(ch) {
    if (ch === ' ') return 6;
    const face = GLYPHS[ch];
    if (!face) return LINE;
    return face.w === 6 ? 7 : LINE;
  }

  function textWidth(text) {
    let width = 0;
    for (let i = 0; i < text.length; i++) width += advance(text.charAt(i));
    return width;
  }

  function blit(ctx, face, x, y) {
    for (let py = 0; py < face.h; py++) {
      const bits = face.rows[py];
      for (let px = 0; px < face.w; px++) {
        if (bits & (1 << (face.w - 1 - px))) ctx.fillRect(x + px, y + py, 1, 1);
      }
    }
  }

  function drawText(ctx, text, x, y, color) {
    ctx.fillStyle = color;
    let cx = x;
    for (let i = 0; i < text.length; i++) {
      const ch = text.charAt(i);
      if (ch === ' ') {
        cx += 6;
        continue;
      }
      const face = GLYPHS[ch];
      if (!face) {
        cx += LINE;
        continue;
      }
      blit(ctx, face, cx, y + (LINE - face.h));
      cx += face.w === 6 ? 7 : LINE;
    }
    return cx;
  }

  return {
    glyph: glyph,
    textWidth: textWidth,
    drawText: drawText,
  };
